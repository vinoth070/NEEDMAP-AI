/**
 * Attaches realistic campus landmark coordinates to mapped demo opportunity clusters
 * while intentionally leaving non-spatial administrative clusters unmapped so the UI
 * honestly demonstrates both geo-tagged and unmapped opportunity handling.
 */
export function enrichDemoOpportunitiesWithLocations(
  opportunities: OpportunityCluster[]
): OpportunityCluster[] {
  return opportunities.map((opp) => {
    const lowerTitle = opp.title.toLowerCase();
    if (lowerTitle.includes('wi-fi') || lowerTitle.includes('hostel')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-IT',
        coordinates: {
          lat: 13.0127,
          lng: 80.2343,
          locationLabel: 'North & East Hostel Blocks B/C',
        },
      };
    }
    if (lowerTitle.includes('accessibility') || lowerTitle.includes('elevator') || lowerTitle.includes('ramp')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-FAC',
        coordinates: {
          lat: 13.0117,
          lng: 80.2364,
          locationLabel: 'Science Annex & East Library Entrance',
        },
      };
    }
    if (lowerTitle.includes('canteen') && lowerTitle.includes('queue')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-ACAD',
        coordinates: {
          lat: 13.0102,
          lng: 80.2355,
          locationLabel: 'Central Canteen Dining Hall',
        },
      };
    }
    if (lowerTitle.includes('allergen') || lowerTitle.includes('dietary')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-ACAD',
        coordinates: {
          lat: 13.0100,
          lng: 80.2358,
          locationLabel: 'Central Canteen Serving Counter',
        },
      };
    }
    if (lowerTitle.includes('lecture hall') || lowerTitle.includes('projector') || lowerTitle.includes('av')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-FAC',
        coordinates: {
          lat: 13.0111,
          lng: 80.2350,
          locationLabel: 'Lecture Halls 201–204 & Auditorium B',
        },
      };
    }
    if (lowerTitle.includes('waste') || lowerTitle.includes('recycling')) {
      return {
        ...opp,
        assignedDepartmentId: 'DEPT-SAN',
        coordinates: {
          lat: 13.0094,
          lng: 80.2347,
          locationLabel: 'South Quad & Hostel Outdoor Walkways',
        },
      };
    }
    // Administrative / Registrar online portal cluster intentionally has NO map pin fabricated
    return {
      ...opp,
      assignedDepartmentId: 'DEPT-ACAD',
    };
  });
}
